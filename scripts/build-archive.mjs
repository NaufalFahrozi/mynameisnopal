// Builds src/data/letterboxd-archive.ts from an extracted Letterboxd export.
// Usage: node scripts/build-archive.mjs <path-to-extracted-export-dir>
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: node scripts/build-archive.mjs <path-to-extracted-export-dir>');
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (ch !== '\r') {
      field += ch;
    }
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function load(file) {
  const text = readFileSync(join(dir, file), 'utf8');
  const rows = parseCsv(text);
  const header = rows.shift();
  return rows
    .filter((r) => r.length === header.length)
    .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

const watched = load('watched.csv');
const ratings = load('ratings.csv');
const diary = load('diary.csv');
const reviews = load('reviews.csv');

const dist = new Map();
for (const r of ratings) {
  const v = Number(r.Rating);
  if (!Number.isFinite(v)) continue;
  dist.set(v, (dist.get(v) ?? 0) + 1);
}
const ratingDistribution = [0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 4.5, 5].map((rating) => ({
  rating,
  count: dist.get(rating) ?? 0,
}));

const perYear = new Map();
for (const w of watched) {
  const year = (w.Date || '').slice(0, 4);
  if (!/^\d{4}$/.test(year)) continue;
  perYear.set(year, (perYear.get(year) ?? 0) + 1);
}
const filmsPerYear = [...perYear.entries()]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([year, count]) => ({ year, count }));

const ratedCount = ratings.length;
const avg = ratedCount ? [...dist.entries()].reduce((s, [v, c]) => s + v * c, 0) / ratedCount : 0;

const archive = {
  source: 'letterboxd export, 2026-10-19',
  totals: {
    watched: watched.length,
    rated: ratedCount,
    diary: diary.length,
    reviews: reviews.length,
  },
  averageRating: Number(avg.toFixed(2)),
  ratingDistribution,
  filmsPerYear,
};

const out = `// Generated by scripts/build-archive.mjs from the Letterboxd export. Do not edit by hand.

export const archive = ${JSON.stringify(archive, null, 2)};
`;

writeFileSync(resolve(process.cwd(), 'src/data/letterboxd-archive.ts'), out, 'utf8');
console.log(
  `archive written: ${watched.length} watched, ${ratedCount} rated, ${reviews.length} reviews`,
);
