// Refreshes the committed Letterboxd cache.
// Run: npm run sync   (also runs daily in .github/workflows/sync-letterboxd.yml)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFeed } from '../src/lib/parse-letterboxd.ts';

const FEED_URL = 'https://letterboxd.com/NaufalFahrozi/rss/';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../src/data/letterboxd-cache.ts');

const res = await fetch(FEED_URL, {
  headers: { 'user-agent': 'mynameisnopal/1.0 (letterboxd cache sync)' },
});
if (!res.ok) throw new Error(`Letterboxd feed responded HTTP ${res.status}`);

const logs = parseFeed(await res.text());
if (!logs.length) throw new Error('Feed parsed to zero entries — refusing to overwrite the cache.');

const fetchedAt = new Date().toISOString();
const contents = `// Generated by scripts/sync-letterboxd.mjs — do not edit by hand.
// Last sync: ${fetchedAt}

export const fetchedAt = ${JSON.stringify(fetchedAt)};

export const cache = ${JSON.stringify(logs, null, 2)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, contents, 'utf8');
console.log(`Wrote ${logs.length} entries to src/data/letterboxd-cache.ts (${fetchedAt})`);
